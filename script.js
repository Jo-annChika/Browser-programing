console.log("Portfolio loaded – Jo-ann Obewe");
 
// --- State variable (L04) ---
let isDark = false;
 
// --- Restore saved theme from localStorage on page load (L05) ---
const savedTheme = localStorage.getItem("portfolio_theme");
if (savedTheme === "dark") {
    document.body.classList.add("dark");
    document.body.classList.remove("light");
    isDark = true;
    const btn = document.getElementById("themeToggle");
    if (btn) btn.textContent = "☀️";
    console.log("Theme restored: dark");
} else {
    console.log("Theme restored: light");
}
 
// --- setTheme function (L04) ---
function setTheme(dark) {
    if (dark) {
        document.body.classList.add("dark");
        document.body.classList.remove("light");
        localStorage.setItem("portfolio_theme", "dark");
        const btn = document.getElementById("themeToggle");
        if (btn) btn.textContent = "☀️";
        console.log("Theme changed: dark");
    } else {
        document.body.classList.remove("dark");
        document.body.classList.add("light");
        localStorage.setItem("portfolio_theme", "light");
        const btn = document.getElementById("themeToggle");
        if (btn) btn.textContent = "🌙";
        console.log("Theme changed: light");
    }
}
 
// --- Event listener: theme toggle button (L04) ---
const themeBtn = document.getElementById("themeToggle");
if (themeBtn) {
    themeBtn.addEventListener("click", function () {
        isDark = !isDark;
        setTheme(isDark);
    });
}
 
// --- Event listener: mobile burger menu (L04) ---
const burger   = document.getElementById("burger");
const navLinks = document.getElementById("navLinks");
if (burger && navLinks) {
    burger.addEventListener("click", function () {
        navLinks.classList.toggle("open");
        console.log("Mobile menu toggled");
    });
}
 
// --- showGreeting function (L04) ---
function showGreeting() {
    const hour = new Date().getHours();
    let greeting = "Welcome";
    if (hour < 12)      greeting = "Good morning";
    else if (hour < 18) greeting = "Good afternoon";
    else                greeting = "Good evening";
    console.log(greeting + " – thanks for visiting Jo-ann's portfolio!");
}
showGreeting();
 
