// Why do we use async/await?
// async/await makes asynchronous code look and behave like
// normal sequential code. Without it we would have to chain
// .then() callbacks which become hard to read and maintain.
 
// Why do we check response.ok?
// fetch() does NOT automatically throw an error for HTTP error
// codes like 404 or 500. Checking response.ok lets us catch
// those failures and handle them ourselves instead of using bad data.
 
// Why do we use try/catch?
// Network requests can fail for many reasons such as no internet
// connection or the server being down. try/catch lets us handle
// those errors gracefully and show the user a clear message
// instead of the page crashing silently.
 
const loadDataBtn = document.getElementById("loadDataBtn");
const dataBox     = document.getElementById("dataBox");
 
async function loadUserData() {
    dataBox.innerHTML = "<p>Loading…</p>";
    console.log("Fetching data from API…");
 
    try {
        const response = await fetch("https://jsonplaceholder.typicode.com/users/1");
 
        if (!response.ok) {
            throw new Error("HTTP error: " + response.status);
        }
 
        const user = await response.json();
        console.log("Data loaded:", user.name);
 
        dataBox.innerHTML =
            "<p><strong>Name:</strong> "    + user.name         + "</p>" +
            "<p><strong>Email:</strong> "   + user.email        + "</p>" +
            "<p><strong>Company:</strong> " + user.company.name + "</p>";
 
    } catch (error) {
        console.log("Error:", error.message);
        dataBox.innerHTML = "<p>Error loading data. Please try again.</p>";
    }
}
 
if (loadDataBtn) {
    loadDataBtn.addEventListener("click", function () {
        console.log("Load Data button clicked");
        loadUserData();
    });
}
 